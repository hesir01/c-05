#include <bits/stdc++.h>
using namespace std;
/*
思路：
1、第十天早上只剩下 1 个桃子；
2、每天吃的是前一天剩下的一半再多一个，也就是：
   当天剩下的桃子 = 前一天剩下的桃子 - (前一天剩下的桃子 / 2 + 1)
   化简得：前一天剩下的桃子 = (当天剩下的桃子 + 1) * 2；
3、从第十天倒着往前推 9 天，就能算出第一天一共摘了多少个桃子；
4、输出第一天摘的桃子数。
*/
long long x;

int main() {
    x = 1;  // 第十天剩下的桃子数

    // 从第九天倒推到第一天，共推 9 次
    for (int i = 1; i <= 9; ++i) {
        x = (x + 1) * 2;
    }

    cout << x << endl;

    return 0;
}
