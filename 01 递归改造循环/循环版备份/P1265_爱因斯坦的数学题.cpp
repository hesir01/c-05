#include <bits/stdc++.h>
using namespace std;
/*
思路：
1、题目要求阶梯数最少，且跨 7 阶正好不剩，说明该数是 7 的倍数；
2、从最小的 7 的倍数开始枚举 x = 7, 14, 21, ...；
3、逐个检查：x%2==1（剩1阶）、x%3==2（剩2阶）、
   x%5==4（剩4阶）、x%6==5（剩5阶）；
4、第一个同时满足四个条件的 x 就是答案。
*/
int x;

int main() {
    // 从小到大枚举 7 的倍数
    for (x = 7; ; x += 7) {
        // 同时满足题目中的四个余数条件
        if (x % 2 == 1 && x % 3 == 2 && x % 5 == 4 && x % 6 == 5) {
            cout << x << endl;
            break;
        }
    }

    return 0;
}
