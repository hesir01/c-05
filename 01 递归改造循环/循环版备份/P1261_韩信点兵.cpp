#include <bits/stdc++.h>
using namespace std;
/*
思路：
1、题目条件翻译成余数：
   按 1~5 报数最后报 1，即人数 %5==1；
   按 1~6 报数最后报 5，即人数 %6==5；
   按 1~7 报数最后报 4，即人数 %7==4；
   按 1~11 报数最后报 10，即人数 %11==10；
2、从 1 开始从小到大枚举人数 x；
3、第一个同时满足四个条件的 x 就是答案。
*/
int x;

int main() {
    // 从小到大枚举人数
    for (x = 1; ; ++x) {
        // 同时满足四个报数条件
        if (x % 5 == 1 && x % 6 == 5 && x % 7 == 4 && x % 11 == 10) {
            cout << x << endl;
            break;
        }
    }

    return 0;
}
