#include <bits/stdc++.h>
using namespace std;
/*
思路：
1、题目条件翻译成余数：
   按 1~5 报数最后报 1，即人数 %5==1；
   按 1~6 报数最后报 5，即人数 %6==5；
   按 1~7 报数最后报 4，即人数 %7==4；
   按 1~11 报数最后报 10，即人数 %11==10；
2、递归函数 find(x)：检查人数 x 是否同时满足四个条件；
   满足：出口，返回 x；
   不满足：递归 find(x + 1)，检查下一个人数；
3、main 输出 find(1)，第一个满足条件的 x 就是最少人数。
*/
// 递归找满足四个报数条件的最少人数
int find(int x) {
    if (x % 5 == 1 && x % 6 == 5 && x % 7 == 4 && x % 11 == 10) {
        return x;               // 出口：找到答案
    }
    return find(x + 1);         // 递归检查下一个数
}

int main() {
    cout << find(1) << endl;
    return 0;
}
